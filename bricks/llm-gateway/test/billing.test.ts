/** A provider that answers with fixed token counts (or throws), records what it was asked, and can be held at a gate. */
class FakeProvider implements LlmProviderAdapter {
  calls: Array<{ prompt: string; model: string; options: { temperature?: number; maxTokens?: number } | undefined }> = [];
  gate: Promise<void> | undefined;
  constructor(
    public readonly name = "fake",
    public tokens = { promptTokens: 150, completionTokens: 50 },
    public failWith?: string,
  ) {}
  async generate(prompt: string, model: string, options?: { temperature?: number; maxTokens?: number }) {
    this.calls.push({ prompt, model, options });
    if (this.gate) await this.gate;
    if (this.failWith) throw new Error(this.failWith);
    return { text: `generated by ${model}`, ...this.tokens, modelUsed: model };
  }
}

type Entry = { workspaceId: string; credits: number; key: string; reason: string; userId?: string };

/**
 * An in-memory wallet with the charger's shape, in the real wallet's order: a debit checks the balance first and the
 * key second (so a retry after a committed attempt can be refused for the balance), refuses an overdraw, and is atomic
 * per call. A refund pays back at most what the debit under `againstKey` took, and nothing if there is none.
 * Story 2.5: the charger interface speaks thousandths of a credit; this fake keeps whole credits for readable
 * expectations, converts at its boundary, and records every raw thousandths amount it was handed in `milliSeen`.
 */
class FakeCharger implements CreditCharger {
  balances = new Map<string, number>();
  debits: Entry[] = [];
  refunds: Entry[] = [];
  milliSeen: number[] = [];
  async balanceMilli(_db: D1Like, workspaceId: string) {
    return (this.balances.get(workspaceId) ?? 0) * 1000;
  }
  async debit(_db: D1Like, workspaceId: string, milli: number, key: string, reason: string, userId?: string): Promise<ChargeOutcome> {
    this.milliSeen.push(milli);
    const credits = milli / 1000;
    const balance = this.balances.get(workspaceId) ?? 0;
    if (balance < credits) return { ok: false, code: "INSUFFICIENT_CREDITS" };
    if (this.debits.some((d) => d.workspaceId === workspaceId && d.key === key)) return { ok: true };
    this.balances.set(workspaceId, balance - credits);
    this.debits.push({ workspaceId, credits, key, reason, ...(userId ? { userId } : {}) });
    return { ok: true };
  }
  async refund(_db: D1Like, workspaceId: string, milli: number, key: string, againstKey: string, reason: string, userId?: string): Promise<ChargeOutcome> {
    this.milliSeen.push(milli);
    const credits = milli / 1000;
    const debit = this.debits.find((d) => d.workspaceId === workspaceId && d.key === againstKey);
    if (!debit) return { ok: false, code: "NOTHING_TO_REFUND" };
    if (this.refunds.some((d) => d.workspaceId === workspaceId && d.key === key)) return { ok: true };
    const amount = Math.min(credits, debit.credits);
    this.balances.set(workspaceId, (this.balances.get(workspaceId) ?? 0) + amount);
    this.refunds.push({ workspaceId, credits: amount, key, reason, ...(userId ? { userId } : {}) });
    return { ok: true };
  }
  async settled(_db: D1Like, workspaceId: string, key: string) {
    const entry = [...this.debits, ...this.refunds].find((d) => d.workspaceId === workspaceId && d.key === key);
    return entry ? { milli: entry.credits * 1000 } : null;
  }
}

/** A charger whose every method is a spy that fails the test if called. */
function untouchableCharger() {
  const fail = () => {
    throw new Error("the charger must not be called");
  };
  return { balanceMilli: vi.fn(fail), debit: vi.fn(fail), refund: vi.fn(fail), settled: vi.fn(fail) };
}

function appWith(options: AiRouteOptions, role = "member", ws = WS_A): Hono<AiEnv> {
  const app = new Hono<AiEnv>();
  app.use("*", async (c, next) => {
    c.set("workspace", { id: ws, role });
    c.set("user", { uid: USER });
    c.set("ctx", Object.freeze({ userId: USER, workspaceId: ws, role }));
    await next();
  });
  app.route("/api", createAiRoutes(options));
  return app;
}

async function generate(app: Hono<AiEnv>, body: unknown): Promise<{ status: number; json: Record<string, unknown>; text: string }> {
  const res = await app.fetch(
    new Request("http://localhost/api/ai/generate", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }),
    { DB: db },
  );
  const text = await res.text();
  return { status: res.status, json: JSON.parse(text) as Record<string, unknown>, text };
}

async function logRows(ws = WS_A) {
  return (
    await db
      .prepare("SELECT id, model, prompt_tokens, completion_tokens, cost_credits, billing_status FROM ai_generation_logs WHERE workspace_id = ? ORDER BY rowid")
      .bind(ws)
      .all<{ id: string; model: string; prompt_tokens: number; completion_tokens: number; cost_credits: number; billing_status: string }>()
  ).results;
}

