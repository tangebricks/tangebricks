describe("providers come from the app only (story 1.13)", () => {
  it("a body naming providers is ignored: it cannot add a fallback or satisfy the configured check", async () => {
    const primary = new FakeProvider("fake", undefined, "primary down");
    const backup = new FakeProvider("backup");
    const charger = new FakeCharger();
    charger.balances.set(WS_A, 100);
    vi.spyOn(console, "error").mockImplementation(() => {});

    // The primary fails; the body's fallback is not used.
    const ignored = await generate(appWith({ adapters: [primary, backup], provider: "fake", charger }), {
      prompt: "Hello",
      provider: "backup",
      fallbackProviders: ["backup"],
    });
    expect(ignored.status).toBe(502);
    expect(backup.calls).toHaveLength(0);

    // Only "backup" is connected and the app's provider is not: the body cannot make the call configured.
    const notConfigured = await generate(appWith({ adapters: [backup], provider: "fake", charger }), { prompt: "Hello", fallbackProviders: ["backup"] });
    expect(notConfigured.status).toBe(503);
    expect(notConfigured.json.code).toBe("NOT_CONFIGURED");
    expect(backup.calls).toHaveLength(0);

    // The app's own fallback list is used.
    const configured = await generate(appWith({ adapters: [primary, backup], provider: "fake", charger, fallbackProviders: "backup" }), { prompt: "Hello" });
    expect(configured.status, configured.text).toBe(200);
    expect(configured.json.result).toMatchObject({ provider: "backup" });
    expect(charger.balances.get(WS_A)).toBe(99);
  });
});

describe("error redaction and refunds on provider failure (story 1.13)", () => {
  it("a provider failure answers 502 PROVIDER_ERROR with a fixed message; the reservation is refunded in full", async () => {
    const secret = "Incorrect API key provided: sk-live-SECRET123 for https://api.provider.test";
    const charger = new FakeCharger();
    charger.balances.set(WS_A, 100);
    const logged = vi.spyOn(console, "error").mockImplementation(() => {});
    const res = await generate(
      appWith({
        adapters: [new FakeProvider("fake", undefined, secret), new FakeProvider("backup", undefined, "backup down")],
        provider: "fake",
        fallbackProviders: ["backup"],
        charger,
      }),
      { prompt: "Hello", maxTokens: 100 },
    );
    expect(res.status).toBe(502);
    expect(res.json).toEqual({ error: "The AI provider could not complete the request", code: "PROVIDER_ERROR", correlationId: expect.stringMatching(/^err_/) });
    expect(res.text).not.toMatch(/SECRET|sk-live|api\.provider|backup down|All LLM providers/);
    const line = logged.mock.calls.find((args) => String(args[0]).includes(res.json.correlationId as string));
    expect(line, "the raw error is logged with the correlation id").toBeDefined();
    expect(charger.debits).toHaveLength(1);
    expect(charger.refunds).toEqual([expect.objectContaining({ credits: charger.debits[0]!.credits, key: `${charger.debits[0]!.key}:refund` })]);
    expect(charger.balances.get(WS_A)).toBe(100);
    expect((await logRows()).map((r) => [r.cost_credits, r.billing_status])).toEqual([[0, "refunded"]]);
    expect(await new LlmGatewayService(db).getUsageStats(WS_A)).toMatchObject({ requestCount: 0 });
  });

  it("a provider failure whose refund also fails is recorded as billing_failed and left out of the usage totals", async () => {
    const charger = new FakeCharger();
    charger.balances.set(WS_A, 100);
    charger.refund = async () => ({ ok: false, code: "WALLET_NOT_FOUND" });
    vi.spyOn(console, "error").mockImplementation(() => {});
    const res = await generate(appWith({ adapters: [new FakeProvider("fake", undefined, "down")], provider: "fake", charger }), { prompt: "Hello", maxTokens: 100 });
    expect(res.status).toBe(502);
    expect((await logRows()).map((r) => [r.cost_credits, r.billing_status])).toEqual([[1, "billing_failed"]]);

    // One delivered generation alongside it: only that one is counted.
    charger.refund = FakeCharger.prototype.refund.bind(charger);
    const ok = await generate(appWith({ adapters: [new FakeProvider()], provider: "fake", charger }), { prompt: "Hello", maxTokens: 100 });
    expect(ok.status).toBe(200);
    expect(await new LlmGatewayService(db).getUsageStats(WS_A)).toEqual({ totalPromptTokens: 150, totalCompletionTokens: 50, totalCostCredits: 1, requestCount: 1 });
  });

  it("an unexpected failure inside generate answers 500 with no raw error", async () => {
    vi.spyOn(LlmGatewayService.prototype, "complete").mockRejectedValue(new Error("SQLITE_ERROR: no such table secret_internal"));
    vi.spyOn(console, "error").mockImplementation(() => {});
    const res = await generate(appWith({ adapters: [new FakeProvider()], provider: "fake", billing: "none" }), { prompt: "Hello" });
    expect(res.status).toBe(500);
    expect(res.json.code).toBe("INTERNAL_ERROR");
    expect(res.text).not.toMatch(/SQLITE|secret_internal/);
  });
});
