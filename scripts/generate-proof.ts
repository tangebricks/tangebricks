// Renders PROOF.md deterministically from evidence/verdicts.json and hypotheses.json.
//
// Usage: node scripts/generate-proof.ts [--root <dir>]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseHypotheses } from "../packages/harness/src/index.ts";
import type { Hypothesis } from "../packages/harness/src/index.ts";
import { INVOICE_FLOW_BLUEPRINT, TWO_BRICK_BLUEPRINT } from "../test/support/blueprints.ts";
import { computeDecision } from "./poc-verdict.ts";
import type { VerdictsFile } from "./poc-verdict.ts";
import { LIVE_HYPOTHESES } from "./proof-inputs.ts";

const repoRoot = resolve(import.meta.dirname, "..");

export function resolveBlueprintIdentity(targetRoot: string = repoRoot, fallbackRoot: string = repoRoot): string {
  const candidates = [
    join(targetRoot, "test", "support", "blueprints.ts"),
    join(fallbackRoot, "test", "support", "blueprints.ts"),
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) {
      const text = readFileSync(candidate, "utf8");
      const match = text.match(/identity\s*:\s*["']([^"']+)["']/);
      if (match?.[1]) return match[1];
    }
  }
  const bpIdentity =
    (INVOICE_FLOW_BLUEPRINT as { identity?: string }).identity ??
    (TWO_BRICK_BLUEPRINT as { identity?: string }).identity ??
    "stub";
  return bpIdentity;
}

export function renderProofMarkdown(
  verdictsData: VerdictsFile,
  hypotheses: ReadonlyArray<Hypothesis>,
  blueprintIdentity: string = "stub",
): string {
  const decision = computeDecision(verdictsData.verdicts);
  const liveSet = new Set<string>(LIVE_HYPOTHESES);
  const totalCount = hypotheses.length;
  const killCount = decision.mechanismKills.length + decision.acceleratorKills.length;

  const lines: string[] = [];
  lines.push("# ProjectX Proof of Concept: Final Verdict Report");
  lines.push("");
  lines.push("**Initiative**: ProjectX Minimalist MVP Proof of Concept  ");
  lines.push(`**Inputs Hash**: \`${verdictsData.inputsHash ?? "unrecorded"}\`  `);
  lines.push(`**Generated By**: \`${verdictsData.generatedBy ?? "node scripts/verify.ts"}\`  `);
  lines.push(`**Verdict**: **${decision.decision.toUpperCase()}**`);
  lines.push("");
  lines.push(`Final initiative verdict: ${decision.decision.toUpperCase()}`);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## 1. Executive Summary");
  lines.push("");
  lines.push(
    `This document is generated deterministically from \`evidence/verdicts.json\` and \`hypotheses.json\` across all ${totalCount} committed hypotheses (H0 through H12; H4 is retired, see docs/retired-hypotheses.md).`,
  );
  lines.push("");
  lines.push("<!-- stats:proof:begin -->");
  lines.push(`- **Hypotheses Evaluated**: ${totalCount}`);
  lines.push(`- **Pass**: ${decision.passes.length}${decision.passes.length > 0 ? ` (${decision.passes.join(", ")})` : ""}`);
  lines.push(`- **Fail**: ${decision.fails.length}${decision.fails.length > 0 ? ` (${decision.fails.join(", ")})` : ""}`);
  lines.push(`- **Kill**: ${killCount}${killCount > 0 ? ` (${[...decision.mechanismKills, ...decision.acceleratorKills].join(", ")})` : ""}`);
  lines.push(`- **Overall Verdict**: **${decision.decision.toUpperCase()}** — ${decision.reasons.join("; ")}`);
  lines.push("<!-- stats:proof:end -->");
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## 2. Hypothesis Register Verdict Table");
  lines.push("");
  lines.push("Each row below reflects the status and measured values recorded in `evidence/verdicts.json`:");
  lines.push("");
  lines.push("| Id | Verdict | Measured | Title | Provenance |");
  lines.push("| :-- | :-- | :-- | :-- | :-- |");

  for (const h of hypotheses) {
    const v = verdictsData.verdicts[h.id];
    if (!v) {
      throw new Error(`Missing verdict entry in verdicts.json for ${h.id}`);
    }
    let provenance: string;
    if (liveSet.has(h.id)) {
      provenance = `recorded live run ${v.recordedAt}`;
    } else if (h.id === "H5") {
      const hostedReason = v.reasons.find((r) => r.startsWith("from the run that started "));
      const hostedAt = hostedReason ? hostedReason.replace("from the run that started ", "").trim() : v.recordedAt;
      provenance = `offline + recorded live run ${hostedAt}`;
    } else {
      provenance = `offline re-measured`;
    }
    lines.push(`| ${h.id} | ${v.verdict} | ${v.measured} | ${h.title} | ${provenance} |`);
  }

  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## 3. Disclosures, Constraints & Derived Caveats");
  lines.push("");

  const h9 = verdictsData.verdicts.H9;
  const h9StatusWord = h9 ? `${h9.verdict} (${h9.measured})` : "unmeasured";
  lines.push("1. **H9 Measurement vs. Deployed Finding**:");
  lines.push(
    `   H9's ${h9?.verdict ?? "result"} was measured in Node (${h9StatusWord}) and the deployed build is a separate finding.`,
  );
  if (h9 && h9.reasons.length > 0) {
    for (const reason of h9.reasons) {
      lines.push(`   - ${reason}`);
    }
  }
  lines.push("");

  lines.push("2. **Authentication Architecture**:");
  if (blueprintIdentity === "stub") {
    lines.push(
      '   The recorded live-account proof blueprints use stub identity behind an access key (derived from blueprint `identity: "stub"`); real Better Auth session authentication on Worker + D1 is available via `core-auth` (`identity: "core-auth"`, verified in `b2b-workspace-app` and `bricks/core-auth/test/better-auth.test.ts`).',
    );
  } else {
    lines.push(
      `   The deployed project used \`${blueprintIdentity}\` identity (derived from blueprint \`identity: "${blueprintIdentity}"\`; real Better Auth session authentication is provided by \`core-auth\`).`,
    );
  }
  lines.push("");

  lines.push("3. **Live-Account Runs**:");
  lines.push("   Hypotheses resting on one run: H10, H11, H12, and the hosted D1 check for H5:");
  for (const liveId of ["H5", ...LIVE_HYPOTHESES]) {
    const v = verdictsData.verdicts[liveId];
    if (!v) continue;
    const startedReason = v.reasons.find((r) => r.startsWith("from the run that started "));
    const runTimestamp =
      liveId === "H5" && startedReason
        ? startedReason.replace("from the run that started ", "").trim()
        : v.recordedAt;
    lines.push(`   - **${liveId}**: recorded live run ${runTimestamp}`);
    for (const reason of v.reasons) {
      lines.push(`     - ${reason}`);
    }
  }
  lines.push("");

  lines.push("4. **Hypothesis Caveats from `hypotheses.json`**:");
  for (const h of hypotheses) {
    if (h.status === "live" && h.caveat) {
      lines.push(`   - **${h.id}**: ${h.caveat}`);
    }
  }
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## 4. Verification Commands");
  lines.push("");
  lines.push("- `pnpm poc:verify`: Runs the test suite, computes `inputsHash`, and writes `evidence/verdicts.json`.");
  lines.push("- `pnpm proof:generate`: Regenerates `PROOF.md` from `evidence/verdicts.json` and `hypotheses.json`.");
  lines.push("- `pnpm proof:check`: Re-runs offline verification into a temporary directory, checks `inputsHash` and `verdicts.json`, and verifies `PROOF.md` matches `proof:generate`.");
  lines.push("- `pnpm poc:verdict`: Evaluates the register's decision rule after verifying `inputsHash` is fresh.");
  lines.push("");

  return lines.join("\n");
}

export function runGenerateProofCli(argv: string[] = process.argv.slice(2)): number {
  let targetRoot = repoRoot;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--root" && argv[i + 1]) {
      targetRoot = resolve(argv[i + 1]!);
      i += 1;
    }
  }

  const verdictsPath = join(targetRoot, "evidence", "verdicts.json");
  const hypothesesPath = existsSync(join(targetRoot, "hypotheses.json"))
    ? join(targetRoot, "hypotheses.json")
    : join(repoRoot, "hypotheses.json");
  const proofPath = join(targetRoot, "PROOF.md");

  if (!existsSync(verdictsPath)) {
    console.error(`Missing verdicts file at ${verdictsPath}: run pnpm poc:verify first`);
    return 2;
  }

  const verdictsData = JSON.parse(readFileSync(verdictsPath, "utf8")) as VerdictsFile;
  const hypotheses = parseHypotheses(JSON.parse(readFileSync(hypothesesPath, "utf8"))).hypotheses;
  const identity = resolveBlueprintIdentity(targetRoot, repoRoot);

  const markdown = renderProofMarkdown(verdictsData, hypotheses, identity);
  writeFileSync(proofPath, markdown, "utf8");
  console.log(`Generated ${proofPath} (inputsHash: ${verdictsData.inputsHash ?? "unrecorded"}).`);
  return 0;
}

const isMain =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
  process.exit(runGenerateProofCli());
}
